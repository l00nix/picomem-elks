typedef uint32_t __u32; typedef uint16_t __u16; typedef uint8_t __u8;
struct super_block { uint16_t sector_size; uint8_t sector_bits; };
#define SECTOR_SIZE_SB(s) ((s)->sector_size)
#define SECTOR_BITS_SB(s) ((s)->sector_bits)
#define MSDOS_DIR_BITS 5
struct msdos_boot_sector {
	char ignored[13];	    /*0*/
	uint8_t cluster_size; /* sectors/cluster 13*/
	uint16_t reserved;    /* reserved sectors 14*/
	uint8_t fats;	    /* number of FATs 16*/
	uint16_t dir_entries; /* root directory entries 17*/
	uint16_t sectors;     /* number of sectors 19*/
	uint8_t media;	    /* media code (unused) 21*/
	uint16_t fat_length;  /* sectors/FAT 22*/
	uint16_t secs_track;  /* sectors per track (unused) 24*/
	uint16_t heads;	    /* number of heads (unused) 26*/
	uint32_t hidden;	    /* hidden sectors 28*/
	uint32_t total_sect;   /* number of sectors (if sectors == 0) 32*/

	/* The following fields are only used by FAT32 */
	__u32	fat32_length;	/* sectors/FAT 36 */
	__u16	flags;		/* bit 8: fat mirroring, low 4: active fat (unused) */
	__u8	version[2];	/* major, minor filesystem version (unused) */
	__u32	root_cluster;	/* first cluster of root directory 44 */
	__u16	info_sector;	/* filesystem info sector (unused) */
	__u16	backup_boot;	/* backup boot sector (unused) */
	__u16	reserved2[6];	/* Unused */
} __attribute__((packed));
static int msdos_valid_geometry(struct super_block *s,
                              struct msdos_boot_sector *b)
{
	uint32_t length = b->fat_length ? b->fat_length : b->fat32_length;
	uint32_t total = b->sectors ? b->sectors : b->total_sect;
	uint32_t data, clusters;

	if (((uint8_t)b->ignored[11] |
	     (uint8_t)b->ignored[12] << 8) != SECTOR_SIZE_SB(s) ||
	    !b->reserved || !b->fats || !length || length > 0xffffU ||
	    !b->cluster_size ||
	    b->cluster_size > 128 || (b->cluster_size & (b->cluster_size - 1)))
		return 0;
	data = b->reserved + (uint32_t)b->fats * length +
		(b->dir_entries >> (SECTOR_BITS_SB(s) - MSDOS_DIR_BITS));
	if (data > 0xffffU || data >= total)
		return 0;
	clusters = (total - data) / b->cluster_size;
	if (!clusters)
		return 0;
	if (!b->fat_length && ((b->flags & 0x80) || b->version[0] ||
	    b->version[1] || b->dir_entries || b->root_cluster < 2 ||
	    b->root_cluster >= clusters + 2 ||
	    b->root_cluster >= length * (SECTOR_SIZE_SB(s) / 4)))
		return 0;
	return 1;
}
struct buffer_head { void *b_data; };
static int maps, releases, logs;
static void map_buffer(struct buffer_head *b) {(void)b;maps++;}
static void unmap_brelse(struct buffer_head *b) {(void)b;releases++;}
#define printk(...) (logs++)
static struct super_block *actual_mount_geometry_gate(struct super_block *s, struct buffer_head *bh) {
 struct msdos_boot_sector *b;
	map_buffer(bh);
	b = (struct msdos_boot_sector *) bh->b_data;
	if (!msdos_valid_geometry(s, b)) {
		unmap_brelse(bh);
		printk("FAT: Unsupported geometry\n");
		return NULL;
	}
 return s; /* Stop before first superblock assignment; not a full mount. */
}
